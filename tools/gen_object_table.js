// Generates src/object_table.cpp from the original decompiled JS object table.
// usage: node tools/gen_object_table.js path/to/src/pako-compression.js > src/object_table.cpp
const fs = require('fs');
const src = fs.readFileSync(process.argv[2], 'utf8').split('\n');
const PRE = 'const colorGreenTint=65280,colorCyanTint=65535,baseUnit=60,physicsConst600=600;';
const start = src.findIndex(l => l.startsWith('const solid2 = '));
const end = src.findIndex(l => l.startsWith('function helperFn18'));
let code = PRE + src.slice(start, end).join('\n') + '\n;module.exports={options8,table3};';
fs.writeFileSync('/tmp/_objtab.js', code);
const { options8, table3 } = require('/tmp/_objtab.js');
const typeMap = { solid: 'Solid', deco: 'Deco', hazard: 'Hazard', portal: 'Portal', pad: 'Pad', ring: 'Ring', trigger: 'Trigger', speed: 'Speed', undefined: 'Deco' };
const q = s => JSON.stringify(s);
const num = n => (Number.isInteger(n) ? n + '.0' : String(n));
let o = '// GENERATED by tools/gen_object_table.js from the original object table. Do not edit.\n#include "level_parser.h"\n\nvoid buildObjectTable(std::unordered_map<int, ObjDef>& t) {\n';
for (const [id, d] of Object.entries(options8)) {
  o += `  { ObjDef d; d.type = DefType::${typeMap[d.type]};`;
  if (d.frame != null) o += ` d.hasFrame = true; d.frame = ${q(d.frame)};`;
  o += ` d.gridW = ${num(d.gridW)}; d.gridH = ${num(d.gridH)};`;
  if ('spriteW' in d) o += ` d.hasSprite = true; d.spriteW = ${num(d.spriteW)}; d.spriteH = ${num(d.spriteH)};`;
  if ('hitboxScaleX' in d) o += ` d.hasHitbox = true; d.hitboxScaleX = ${num(d.hitboxScaleX)}; d.hitboxScaleY = ${num(d.hitboxScaleY)};`;
  if (d.black) o += ' d.black = true;';
  if (d.randomFrames) o += ` d.randomFrames = {${d.randomFrames.map(q).join(', ')}};`;
  if (d.sub) o += ` d.sub = ${q(d.sub)};`;
  if (d.portalParticle) o += ' d.portalParticle = true;';
  if ('portalParticleColor' in d) o += ` d.portalParticleColor = ${d.portalParticleColor};`;
  if ('z' in d) o += ` d.hasZ = true; d.z = ${num(d.z)};`;
  if (d.blend) { if (d.blend !== 'additive') throw new Error('blend ' + d.blend); o += ' d.additive = true;'; }
  if ('tint' in d) o += ` d.hasTint = true; d.tint = ${d.tint};`;
  if (d.enterEffect) o += ` d.enterEffect = ${d.enterEffect};`;
  for (const c of d.children || []) {
    o += ` { ChildDef c; c.frame = ${q(c.frame)};`;
    if ('tint' in c) o += ` c.hasTint = true; c.tint = ${c.tint};`;
    if (c.blend) { if (c.blend !== 'additive') throw new Error('cblend'); o += ' c.additive = true;'; }
    if ('z' in c) o += ` c.hasZ = true; c.z = ${num(c.z)};`;
    if (c.audioScale) o += ' c.audioScale = true;';
    if ('localDy' in c) o += ` c.hasLocalDy = true; c.localDy = ${num(c.localDy)};`;
    o += ' d.children.push_back(c); }';
  }
  o += ` t[${id}] = d; }\n`;
}
o += `  static const int table3[] = {${table3.join(', ')}};\n`;
o += '  for (int id : table3) { auto it = t.find(id); if (it != t.end()) it->second.glow = true; }\n}\n';
process.stdout.write(o);
